CREATE TABLE REGION (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre VARCHAR2(100) NOT NULL,
    CONSTRAINT pk_region PRIMARY KEY (id),
    CONSTRAINT uq_region_nombre UNIQUE (nombre)
);

CREATE TABLE COMUNA (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre VARCHAR2(100) NOT NULL,
    region_id NUMBER NOT NULL,
    CONSTRAINT pk_comuna PRIMARY KEY (id),
    CONSTRAINT fk_comuna_region FOREIGN KEY (region_id) REFERENCES REGION(id) ON DELETE CASCADE,
    CONSTRAINT uq_comuna_region UNIQUE (nombre, region_id)
);

CREATE TABLE CATEGORIA (
    id VARCHAR2(50) NOT NULL,
    nombre VARCHAR2(100) NOT NULL,
    CONSTRAINT pk_categoria PRIMARY KEY (id),
    CONSTRAINT uq_categoria_nombre UNIQUE (nombre)
);

CREATE TABLE PRODUCTO (
    id VARCHAR2(20) NOT NULL,
    nombre VARCHAR2(150) NOT NULL,
    descripcion VARCHAR2(500),
    precio NUMBER(10, 0) NOT NULL,
    precio_oferta NUMBER(10, 0),
    stock NUMBER(6, 0) DEFAULT 0 NOT NULL,
    stock_critico NUMBER(6, 0),
    material VARCHAR2(100),
    img VARCHAR2(500),
    categoria_id VARCHAR2(50) NOT NULL,
    CONSTRAINT pk_producto PRIMARY KEY (id),
    CONSTRAINT fk_producto_categoria FOREIGN KEY (categoria_id) REFERENCES CATEGORIA(id),
    CONSTRAINT ck_producto_precio CHECK (precio >= 0),
    CONSTRAINT ck_producto_oferta CHECK (precio_oferta IS NULL OR (precio_oferta >= 0 AND precio_oferta < precio)),
    CONSTRAINT ck_producto_stock CHECK (stock >= 0)
);

CREATE TABLE USUARIO (
    run VARCHAR2(12) NOT NULL,
    nombre VARCHAR2(100) NOT NULL,
    apellidos VARCHAR2(100) NOT NULL,
    correo VARCHAR2(120) NOT NULL,
    contrasena VARCHAR2(255) NOT NULL,
    fecha_nacimiento DATE,
    rol VARCHAR2(20) DEFAULT 'Cliente' NOT NULL,
    region VARCHAR2(100) NOT NULL,
    comuna VARCHAR2(100) NOT NULL,
    direccion VARCHAR2(200) NOT NULL,
    CONSTRAINT pk_usuario PRIMARY KEY (run),
    CONSTRAINT uq_usuario_correo UNIQUE (correo),
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('Administrador', 'Cliente'))
);

CREATE TABLE ORDEN (
    id VARCHAR2(30) NOT NULL,
    fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    estado VARCHAR2(30) NOT NULL,
    total NUMBER(12, 0) NOT NULL,
    usuario_run VARCHAR2(12),
    cliente_nombre VARCHAR2(100) NOT NULL,
    cliente_apellidos VARCHAR2(100) NOT NULL,
    cliente_correo VARCHAR2(120) NOT NULL,
    direccion VARCHAR2(250) NOT NULL,
    comuna VARCHAR2(100) NOT NULL,
    region VARCHAR2(100) NOT NULL,
    indicaciones VARCHAR2(300),
    CONSTRAINT pk_orden PRIMARY KEY (id),
    CONSTRAINT fk_orden_usuario FOREIGN KEY (usuario_run) REFERENCES USUARIO(run),
    CONSTRAINT ck_orden_estado CHECK (estado IN ('Pagada', 'Pago rechazado')),
    CONSTRAINT ck_orden_total CHECK (total >= 0)
);

CREATE TABLE DETALLE_ORDEN (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    orden_id VARCHAR2(30) NOT NULL,
    producto_id VARCHAR2(20) NOT NULL,
    nombre_producto VARCHAR2(150) NOT NULL,
    precio_unitario NUMBER(10, 0) NOT NULL,
    cantidad NUMBER(6, 0) NOT NULL,
    CONSTRAINT pk_detalle_orden PRIMARY KEY (id),
    CONSTRAINT fk_detalle_orden FOREIGN KEY (orden_id) REFERENCES ORDEN(id) ON DELETE CASCADE,
    CONSTRAINT fk_detalle_producto FOREIGN KEY (producto_id) REFERENCES PRODUCTO(id),
    CONSTRAINT ck_detalle_cantidad CHECK (cantidad >= 1),
    CONSTRAINT ck_detalle_precio CHECK (precio_unitario >= 0)
);

CREATE TABLE BLOG_ARTICULO (
    slug VARCHAR2(100) NOT NULL,
    categoria VARCHAR2(80) NOT NULL,
    titulo VARCHAR2(200) NOT NULL,
    resumen VARCHAR2(500) NOT NULL,
    bajada VARCHAR2(500) NOT NULL,
    img_lista VARCHAR2(500) NOT NULL,
    alt_lista VARCHAR2(200),
    img_detalle VARCHAR2(500) NOT NULL,
    alt_detalle VARCHAR2(200),
    pie_imagen VARCHAR2(300),
    fecha_publicacion DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_blog_articulo PRIMARY KEY (slug)
);

CREATE TABLE BLOG_PARRAFO (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    articulo_slug VARCHAR2(100) NOT NULL,
    orden_parrafo NUMBER(3, 0) NOT NULL,
    contenido VARCHAR2(2000) NOT NULL,
    CONSTRAINT pk_blog_parrafo PRIMARY KEY (id),
    CONSTRAINT fk_parrafo_articulo FOREIGN KEY (articulo_slug) REFERENCES BLOG_ARTICULO(slug) ON DELETE CASCADE,
    CONSTRAINT uq_articulo_orden UNIQUE (articulo_slug, orden_parrafo)
);

CREATE TABLE CONTENIDO_SITIO (
    clave VARCHAR2(60) NOT NULL,
    pagina VARCHAR2(40) NOT NULL,
    titulo VARCHAR2(200) NOT NULL,
    subtitulo VARCHAR2(200),
    descripcion VARCHAR2(1500) NOT NULL,
    img_url VARCHAR2(500),
    img_alt VARCHAR2(200),
    CONSTRAINT pk_contenido_sitio PRIMARY KEY (clave)
);

CREATE TABLE MENSAJE_CONTACTO (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    nombre VARCHAR2(100) NOT NULL,
    correo VARCHAR2(100) NOT NULL,
    comentario VARCHAR2(500) NOT NULL,
    CONSTRAINT pk_mensaje_contacto PRIMARY KEY (id)
);

